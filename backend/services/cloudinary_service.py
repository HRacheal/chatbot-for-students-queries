"""Knowledge-base document storage on Cloudinary.

New uploads use the ``authenticated`` delivery type by default, so files are
only reachable through signed URLs generated by the backend. Files uploaded by
earlier versions of the application were public (``upload`` type); they are
still listed (and flagged as public) but are never moved or deleted
automatically.
"""

import logging
import os
import re
import tempfile
import uuid

import cloudinary
import cloudinary.api
import cloudinary.uploader
import cloudinary.utils
import requests

from config.config import Config

logger = logging.getLogger(__name__)

DELIVERY_TYPES = ("upload", "authenticated")


class StorageNotConfiguredError(RuntimeError):
    pass


class CloudinaryService:
    """Service for managing knowledge-base PDFs in Cloudinary"""

    def __init__(self, settings=None):
        settings = settings or {}
        get = lambda key: settings.get(key, getattr(Config, key))  # noqa: E731
        self.cloud_name = get("CLOUDINARY_CLOUD_NAME")
        self.api_key = get("CLOUDINARY_API_KEY")
        self.api_secret = get("CLOUDINARY_API_SECRET")
        self.folder = get("PDF_FOLDER")
        self.delivery_type = get("CLOUDINARY_DELIVERY_TYPE")
        self.max_download_bytes = get("MAX_DOWNLOAD_MB") * 1024 * 1024
        if self.is_configured():
            cloudinary.config(
                cloud_name=self.cloud_name,
                api_key=self.api_key,
                api_secret=self.api_secret,
                secure=True,
            )

    def is_configured(self):
        return bool(self.cloud_name and self.api_key and self.api_secret)

    def _require_configured(self):
        if not self.is_configured():
            raise StorageNotConfiguredError("Cloudinary credentials are not configured")

    def is_in_managed_folder(self, public_id):
        """True if ``public_id`` lives inside the configured PDF folder."""
        return (
            isinstance(public_id, str)
            and public_id.startswith(self.folder.rstrip("/") + "/")
            and ".." not in public_id
        )

    def upload_pdf(self, pdf_file):
        """Upload a validated PDF (werkzeug FileStorage) to Cloudinary."""
        self._require_configured()
        filename = pdf_file.filename or "document.pdf"
        if not filename.lower().endswith(".pdf"):
            filename += ".pdf"
        sanitized_name = re.sub(r"[^a-zA-Z0-9_]", "_", os.path.splitext(filename)[0])[:80]
        unique_id = f"{sanitized_name}_{uuid.uuid4().hex[:8]}"

        temp_file = tempfile.NamedTemporaryFile(delete=False, suffix=".pdf")
        try:
            pdf_file.stream.seek(0)
            pdf_file.save(temp_file.name)
            temp_file.close()
            options = {
                "resource_type": "raw",
                "type": self.delivery_type,
                "public_id": unique_id,
                "folder": self.folder,
                "overwrite": False,
            }
            if self.delivery_type == "upload":
                options["access_mode"] = "public"
            result = cloudinary.uploader.upload(temp_file.name, **options)
        finally:
            temp_file.close()
            if os.path.exists(temp_file.name):
                os.unlink(temp_file.name)

        result["original_filename"] = filename
        logger.info("Uploaded knowledge-base PDF %s", result.get("public_id"))
        return result

    def list_pdfs(self):
        """List PDFs in the managed folder, for both private and legacy public files."""
        self._require_configured()
        resources = []
        for delivery_type in DELIVERY_TYPES:
            next_cursor = None
            while True:
                params = {
                    "resource_type": "raw",
                    "type": delivery_type,
                    "prefix": self.folder,
                    "max_results": 500,
                }
                if next_cursor:
                    params["next_cursor"] = next_cursor
                result = cloudinary.api.resources(**params)
                resources.extend(result.get("resources", []))
                next_cursor = result.get("next_cursor")
                if not next_cursor:
                    break
        return resources

    def delete_pdf(self, public_id):
        """Delete a PDF, whichever delivery type it was stored with."""
        self._require_configured()
        for delivery_type in DELIVERY_TYPES:
            result = cloudinary.uploader.destroy(
                public_id, resource_type="raw", type=delivery_type, invalidate=True
            )
            if result.get("result") == "ok":
                logger.info("Deleted knowledge-base PDF %s", public_id)
                return result
        return {"result": "not found"}

    def file_url(self, resource):
        """URL for a stored file: a signed URL for private files, the public URL otherwise."""
        if resource.get("type") == "authenticated":
            url, _ = cloudinary.utils.cloudinary_url(
                resource["public_id"],
                resource_type="raw",
                type="authenticated",
                sign_url=True,
                secure=True,
            )
            return url
        return resource.get("secure_url") or resource.get("url")

    def download_pdf_bytes(self, resource):
        """Download a stored PDF into memory, enforcing a size limit."""
        url = self.file_url(resource)
        with requests.get(url, stream=True, timeout=(10, 120)) as response:
            response.raise_for_status()
            chunks, total = [], 0
            for chunk in response.iter_content(chunk_size=65536):
                total += len(chunk)
                if total > self.max_download_bytes:
                    raise ValueError("Stored PDF exceeds the maximum download size")
                chunks.append(chunk)
        return b"".join(chunks)
